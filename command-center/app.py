@app.route('/api/content')
@login_required
def api_content():
    """Return media content JSON for the content center."""
    result = {
        'linkedin_posts': [],
        'videos':         [],
        'latest_blog':    None,
    }

    # LinkedIn posts
    posts_file = MEDIA_DIR / 'posts.json'
    if posts_file.exists():
        try:
            data = json.loads(posts_file.read_text())
            result['linkedin_posts'] = data.get('posts', [])
        except Exception:
            pass

    # YouTube videos
    videos_file = MEDIA_DIR / 'videos.json'
    if videos_file.exists():
        try:
            data = json.loads(videos_file.read_text())
            result['videos'] = data.get('videos', [])
        except Exception:
            pass

    # Latest blog post — read from media/blog_posts.json if present
    blog_file = MEDIA_DIR / 'blog_posts.json'
    if blog_file.exists():
        try:
            data = json.loads(blog_file.read_text())
            posts = data.get('posts', [])
            if posts:
                result['latest_blog'] = posts[-1]
        except Exception:
            pass

    return jsonify(result)


