# ─── SSO token helpers ────────────────────────────────────────────────────────

def _generate_sso_token() -> str:
    """Create a signed time-limited token for invoice app SSO."""
    ts  = str(int(time.time()))
    sig = hmac.new(CC_SSO_SECRET.encode(), ts.encode(), hashlib.sha256).hexdigest()
    return f"{ts}.{sig}"


def verify_sso_token(token: str, max_age: int = 90) -> bool:
    """Verify a token generated by _generate_sso_token."""
    try:
        ts, sig = token.split('.', 1)
        expected = hmac.new(CC_SSO_SECRET.encode(), ts.encode(), hashlib.sha256).hexdigest()
        if not hmac.compare_digest(sig, expected):
            return False
        return (int(time.time()) - int(ts)) <= max_age
    except Exception:
        return False


# ─── Auth decorator ───────────────────────────────────────────────────────────

def login_required(f):
    @wraps(f)
    def decorated(*args, **kwargs):
        if not session.get('cc_logged_in'):
            return redirect(url_for('login', next=request.path))
        return f(*args, **kwargs)
    return decorated


# ─── Core routes ──────────────────────────────────────────────────────────────

@app.route('/login', methods=['GET', 'POST'])
def login():
    if session.get('cc_logged_in'):
        return redirect(url_for('dashboard'))
    error = None
    if request.method == 'POST':
        if request.form.get('password', '') == CC_PASSWORD:
            session['cc_logged_in']  = True
            session.permanent        = True
            nxt = request.form.get('next') or url_for('dashboard')
            return redirect(nxt)
        error = 'Incorrect password. Please try again.'
    return render_template('login.html', error=error,
                           next=request.args.get('next', ''))


@app.route('/logout')
def logout():
    session.clear()
    return redirect(url_for('login'))


